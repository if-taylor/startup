
const express = require('express');
const cookieParser = require('cookie-parser');
const bcrypt = require('bcryptjs');
const { randomUUID } = require('crypto');

const app = express();
const authCookieName = 'token';

// Temporary in-memory storage
let users = [];
let goals = [];
let habits = [];
let events = [];

const port = process.argv.length > 2 ? process.argv[2] : 4000;

app.set('trust proxy', 1);
app.use(express.json());
app.use(cookieParser());
app.use(express.static('public'));

const apiRouter = express.Router();
app.use('/api', apiRouter);

// Test endpoint
apiRouter.get('/status', (req, res) => {
    res.send({ status: 'LiveMyGoals service is running' });
});

// Create a new account
apiRouter.post('/auth/create', async (req, res) => {
    const { email, password } = req.body;

    if (typeof email !== 'string' || !email.trim() ||
        typeof password !== 'string' || !password) {
        return res.status(400).send({ message: 'Email and password are required' });
    }

    if (users.find((user) => user.email === email)) {
        return res.status(409).send({ message: 'Account already exists' });
    }

    const user = {
        email: email,
        password: await bcrypt.hash(password, 10),
        token: randomUUID(),
    };

    users.push(user);
    setAuthCookie(res, user.token, req);

    res.status(201).send({ email: user.email });
});

// Log in to an existing account
apiRouter.post('/auth/login', async (req, res) => {
    const { email, password } = req.body;

    const user = users.find((user) => user.email === email);

    if (!user || typeof password !== 'string' ||
        !(await bcrypt.compare(password, user.password))) {
        return res.status(401).send({ message: 'Invalid email or password' });
    }

    user.token = randomUUID();
    setAuthCookie(res, user.token, req);

    res.send({ email: user.email });
});

// Log out
apiRouter.delete('/auth/logout', (req, res) => {
    const user = users.find((user) => user.token === req.cookies[authCookieName]);

    if (user) {
        user.token = null;
    }

    res.clearCookie(authCookieName, { path: '/' });
    res.status(204).end();
});

// Check current authentication
apiRouter.get('/auth/me', (req, res) => {
    const user = users.find((user) => user.token === req.cookies[authCookieName]);

    if (!user) {
        return res.status(401).send({ message: 'Not authenticated' });
    }

    res.send({ email: user.email });
});

// Authentication cookie helper
function setAuthCookie(res, token, req) {
    res.cookie(authCookieName, token, {
        secure: req.secure,
        httpOnly: true,
        sameSite: 'lax',
        maxAge: 1000 * 60 * 60 * 24 * 7,
        path: '/',
    });
}


//
// Middleware to verify authentication
//
function requireAuth(req, res, next) {
    const token = req.cookies[authCookieName];

    if (!token) {
        return res.status(401).send({ message: 'Not authenticated' });
    }

    const user = users.find((user) => user.token === token);

    if (!user) {
        return res.status(401).send({ message: 'Not authenticated' });
    }

    req.user = user;
    next();
}

//
// GET /api/goals - Retrieve user's goals
//
apiRouter.get('/goals', requireAuth, (req, res) => {
    const userGoals = goals.filter(
        (goal) => goal.owner === req.user.email
    );

    res.send(userGoals);
});

//
// POST /api/goals - Create a new goal
//
apiRouter.post('/goals', requireAuth, (req, res) => {
    const { name, dueDate, tasks, completedDate } = req.body;

    if (typeof name !== 'string' || !name.trim()) {
        return res.status(400).send({
            message: 'Goal name is required',
        });
    }

    if (!Array.isArray(tasks) || tasks.some(
        (task) => !task ||
            typeof task.name !== 'string' ||
            !task.name.trim()
    )) {
        return res.status(400).send({
            message: 'Valid goal tasks are required',
        });
    }

    const goal = {
        id: randomUUID(),
        owner: req.user.email,
        name: name.trim(),
        dueDate: typeof dueDate === 'string' ? dueDate : '',
        tasks: tasks.map((task) => ({
            id: randomUUID(),
            name: task.name.trim(),
            completed: task.completed === true,
            autoGenerated: task.autoGenerated === true,
        })),
        completedDate: typeof completedDate === 'string'
            ? completedDate
            : null,
    };

    goals.push(goal);
    res.status(201).send(goal);
});

//
// PUT /api/goals/:id - Update an existing goal
//
apiRouter.put('/goals/:id', requireAuth, (req, res) => {
    const goal = goals.find(
        (goal) =>
            goal.id === req.params.id &&
            goal.owner === req.user.email
    );

    if (!goal) {
        return res.status(404).send({
            message: 'Goal not found',
        });
    }

    const { name, dueDate, tasks, completedDate } = req.body;

    if (name !== undefined) {
        if (typeof name !== 'string' || !name.trim()) {
            return res.status(400).send({
                message: 'Goal name cannot be empty',
            });
        }
    }

    if (tasks !== undefined &&
        (!Array.isArray(tasks) || tasks.some(
            (task) => !task ||
                typeof task.name !== 'string' ||
                !task.name.trim()
        ))) {
        return res.status(400).send({
            message: 'Invalid goal tasks',
        });
    }

    if (name !== undefined) {
        goal.name = name.trim();
    }

    if (dueDate !== undefined) {
        goal.dueDate = dueDate;
    }

    if (tasks !== undefined) {
        goal.tasks = tasks.map((task) => ({
            id: task.id || randomUUID(),
            name: task.name.trim(),
            completed: task.completed === true,
            autoGenerated: task.autoGenerated === true,
        }));
    }

    if (completedDate !== undefined) {
        goal.completedDate = completedDate;
    }

    res.send(goal);
});

//
// DELETE /api/goals/:id - Delete a goal
//
apiRouter.delete('/goals/:id', requireAuth, (req, res) => {
    const index = goals.findIndex(
        (goal) =>
            goal.id === req.params.id &&
            goal.owner === req.user.email
    );

    if (index === -1) {
        return res.status(404).send({
            message: 'Goal not found',
        });
    }

    goals.splice(index, 1);
    res.status(204).end();
});


app.listen(port, () => {
    console.log(`LiveMyGospel service listening on port ${port}`);
});
