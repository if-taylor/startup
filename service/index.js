
const express = require('express');
const cookieParser = require('cookie-parser');
const bcrypt = require('bcryptjs');
const { randomUUID } = require('crypto');
const database = require('./database.js');

const app = express();
const authCookieName = 'token';

const port = process.argv.length > 2 ? process.argv[2] : 4000;

app.set('trust proxy', 1);
app.use(express.json());
app.use(cookieParser());
app.use(express.static('public'));

const apiRouter = express.Router();
app.use('/api', apiRouter);

// Test endpoint
apiRouter.get('/status', (req, res) => {
    res.send({ status: 'LiveMyGospel service is running' });
});

// Create a new account
apiRouter.post('/auth/create', async (req, res) => {
    const { email, password } = req.body;

    if (typeof email !== 'string' || !email.trim() ||
        typeof password !== 'string' || !password) {
        return res.status(400).send({ message: 'Email and password are required' });
    }

    const existingUser = await database.userCollection.findOne({ email });

    if (existingUser) {
        return res.status(409).send({ message: 'Account already exists' });
    }

    const user = {
        email,
        password: await bcrypt.hash(password, 10),
        token: randomUUID(),
    };

    try {
        await database.userCollection.insertOne(user);
    } catch (error) {
        if (error.code === 11000) {
            return res.status(409).send({ message: 'Account already exists' });
        }
        throw error;
    }

    setAuthCookie(res, user.token, req);
    res.status(201).send({ email: user.email });
});

// Log in to an existing account
apiRouter.post('/auth/login', async (req, res) => {
    const { email, password } = req.body;

    const user = await database.userCollection.findOne({ email });

    if (!user || typeof password !== 'string' ||
        !(await bcrypt.compare(password, user.password))) {
        return res.status(401).send({ message: 'Invalid email or password' });
    }

    const token = randomUUID();

    await database.userCollection.updateOne(
        { email },
        { $set: { token } }
    );

    setAuthCookie(res, token, req);
    res.send({ email: user.email });
});

// Log out
apiRouter.delete('/auth/logout', async (req, res) => {
    const token = req.cookies[authCookieName];

    if (token) {
        await database.userCollection.updateOne(
            { token },
            { $set: { token: null } }
        );
    }

    res.clearCookie(authCookieName, { path: '/' });
    res.status(204).end();
});

// Check current authentication
apiRouter.get('/auth/me', async (req, res) => {
    const token = req.cookies[authCookieName];

    const user = token
        ? await database.userCollection.findOne({ token })
        : null;

    if (!user) {
        return res.status(401).send({ message: 'Not authenticated' });
    }

    res.send({ email: user.email });
});

// Authentication cookie helper
function setAuthCookie(res, token, req) {
    res.cookie(authCookieName, token, {
        secure: req.secure,
        httpOnly: true,
        sameSite: 'lax',
        maxAge: 1000 * 60 * 60 * 24 * 7,
        path: '/',
    });
}


// Middleware to verify authentication
async function requireAuth(req, res, next) {
    try {
        const token = req.cookies[authCookieName];

        if (!token) {
            return res.status(401).send({ message: 'Not authenticated' });
        }

        const user = await database.userCollection.findOne({ token });

        if (!user) {
            return res.status(401).send({ message: 'Not authenticated' });
        }

        req.user = user;
        next();
    } catch (error) {
        next(error);
    }
}

// GET /api/goals - Retrieve user's goals
apiRouter.get('/goals', requireAuth, async (req, res) => {
    const userGoals = await database.goalCollection
        .find({ owner: req.user.email }, { projection: { _id: 0 } })
        .toArray();

    res.send(userGoals);
});

// POST /api/goals - Create a new goal
apiRouter.post('/goals', requireAuth, async (req, res) => {
    const { name, dueDate, tasks, completedDate } = req.body;

    if (typeof name !== 'string' || !name.trim()) {
        return res.status(400).send({
            message: 'Goal name is required',
        });
    }

    if (!Array.isArray(tasks) || tasks.some(
        (task) => !task ||
            typeof task.name !== 'string' ||
            !task.name.trim()
    )) {
        return res.status(400).send({
            message: 'Valid goal tasks are required',
        });
    }

    const goal = {
        id: randomUUID(),
        owner: req.user.email,
        name: name.trim(),
        dueDate: typeof dueDate === 'string' ? dueDate : '',
        tasks: tasks.map((task) => ({
            id: randomUUID(),
            name: task.name.trim(),
            completed: task.completed === true,
            autoGenerated: task.autoGenerated === true,
        })),
        completedDate: typeof completedDate === 'string'
            ? completedDate
            : null,
    };

    await database.goalCollection.insertOne(goal);

    res.status(201).send({
        id: goal.id,
        owner: goal.owner,
        name: goal.name,
        dueDate: goal.dueDate,
        tasks: goal.tasks,
        completedDate: goal.completedDate,
    });
});

// PUT /api/goals/:id - Update an existing goal
apiRouter.put('/goals/:id', requireAuth, async (req, res) => {
    const filter = {
        id: req.params.id,
        owner: req.user.email,
    };

    const goal = await database.goalCollection.findOne(filter);

    if (!goal) {
        return res.status(404).send({
            message: 'Goal not found',
        });
    }

    const { name, dueDate, tasks, completedDate } = req.body;

    if (name !== undefined) {
        if (typeof name !== 'string' || !name.trim()) {
            return res.status(400).send({
                message: 'Goal name cannot be empty',
            });
        }
    }

    if (tasks !== undefined &&
        (!Array.isArray(tasks) || tasks.some(
            (task) => !task ||
                typeof task.name !== 'string' ||
                !task.name.trim()
        ))) {
        return res.status(400).send({
            message: 'Invalid goal tasks',
        });
    }

    const updates = {};

    if (name !== undefined) {
        updates.name = name.trim();
    }

    if (dueDate !== undefined) {
        updates.dueDate = dueDate;
    }

    if (tasks !== undefined) {
        updates.tasks = tasks.map((task) => ({
            id: task.id || randomUUID(),
            name: task.name.trim(),
            completed: task.completed === true,
            autoGenerated: task.autoGenerated === true,
        }));
    }

    if (completedDate !== undefined) {
        updates.completedDate = completedDate;
    }

    if (Object.keys(updates).length > 0) {
        await database.goalCollection.updateOne(
            filter,
            { $set: updates }
        );
    }

    const updatedGoal = await database.goalCollection.findOne(
        filter,
        { projection: { _id: 0 } }
    );

    res.send(updatedGoal);
});

// DELETE /api/goals/:id - Delete a goal
apiRouter.delete('/goals/:id', requireAuth, async (req, res) => {
    const result = await database.goalCollection.deleteOne({
        id: req.params.id,
        owner: req.user.email,
    });

    if (result.deletedCount === 0) {
        return res.status(404).send({
            message: 'Goal not found',
        });
    }

    res.status(204).end();
});


